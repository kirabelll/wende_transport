@frappe.whitelist()
def get_trip_profitability_report(from_date=None, to_date=None, customer=None, vehicle=None):
	"""
	Returns detailed trip-by-trip profitability analysis.
	"""
	conditions = ["1=1"]
	params = {}

	if from_date:
		conditions.append("t.start_date >= %(from_date)s")
		params["from_date"] = from_date
	if to_date:
		conditions.append("t.start_date <= %(to_date)s")
		params["to_date"] = to_date
	if customer:
		conditions.append("t.customer = %(customer)s")
		params["customer"] = customer
	if vehicle:
		conditions.append("t.vehicle = %(vehicle)s")
		params["vehicle"] = vehicle

	where_str = " AND ".join(conditions)

	return frappe.db.sql(f"""
		SELECT 
			t.name as trip,
			t.start_date,
			t.customer,
			t.vehicle,
			t.driver,
			t.origin,
			t.destination,
			t.cargo_weight,
			t.rate_per_ton,
			t.total_revenue,
			t.advance_amount,
			t.fuel_cost,
			t.total_cost,
			t.net_profit,
			CASE 
				WHEN t.total_revenue > 0 THEN ROUND((t.net_profit / t.total_revenue) * 100, 2)
				ELSE 0.0 
			END as profit_margin_pct,
			t.status,
			t.billing_status
		FROM `tabTrip` t
		WHERE {where_str}
		ORDER BY t.start_date DESC
	""", params, as_dict=True)

@frappe.whitelist()
def get_fuel_efficiency_report(from_date=None, to_date=None):
	"""
	Analyzes fuel consumption, actual km/L vs standard km/L, and variance.
	"""
	conditions = ["1=1"]
	params = {}
	if from_date:
		conditions.append("fl.log_date >= %(from_date)s")
		params["from_date"] = from_date
	if to_date:
		conditions.append("fl.log_date <= %(to_date)s")
		params["to_date"] = to_date

	where_str = " AND ".join(conditions)

	return frappe.db.sql(f"""
		SELECT 
			fl.vehicle,
			COUNT(fl.name) as refill_count,
			COALESCE(SUM(fl.liters), 0) as total_liters,
			COALESCE(SUM(fl.total_amount), 0) as total_fuel_spend,
			COALESCE(MAX(fl.odometer) - MIN(fl.odometer), 0) as km_covered,
			CASE 
				WHEN SUM(fl.liters) > 0 THEN ROUND((MAX(fl.odometer) - MIN(fl.odometer)) / SUM(fl.liters), 2)
				ELSE 0.0 
			END as actual_km_per_liter
		FROM `tabFuel Log` fl
		WHERE {where_str}
		GROUP BY fl.vehicle
		HAVING total_liters > 0
	""", params, as_dict=True)

@frappe.whitelist()
def get_tyre_cost_per_km_report():
	"""
	Evaluates tyre lifecycle economics: purchase cost, total km traversed, and Cost Per Km (CPK).
	"""
	return frappe.db.sql("""
		SELECT 
			serial_number,
			brand,
			size,
			status,
			current_vehicle,
			current_position,
			purchase_cost,
			fitment_km,
			removal_km,
			total_km_run,
			cost_per_km
		FROM `tabTyre Asset`
		ORDER BY cost_per_km ASC, total_km_run DESC
	""", as_dict=True)

@frappe.whitelist()
def get_rental_fleet_margin_report(from_date=None, to_date=None):
	"""
	Evaluates margin and profitability generated by outsourced / rental fleet.
	"""
	conditions = ["1=1"]
	params = {}
	if from_date:
		conditions.append("rt.trip_date >= %(from_date)s")
		params["from_date"] = from_date
	if to_date:
		conditions.append("rt.trip_date <= %(to_date)s")
		params["to_date"] = to_date

	where_str = " AND ".join(conditions)

	return frappe.db.sql(f"""
		SELECT 
			rt.name as rental_trip,
			rt.trip_date,
			rt.rental_vehicle,
			rt.rental_owner,
			rt.customer,
			rt.cargo_weight,
			rt.client_freight_rate,
			rt.owner_agreed_rate,
			rt.total_billed,
			rt.owner_payable,
			rt.company_margin,
			CASE 
				WHEN rt.total_billed > 0 THEN ROUND((rt.company_margin / rt.total_billed) * 100, 2)
				ELSE 0.0 
			END as margin_pct,
			rt.payment_status
		FROM `tabRental Trip` rt
		WHERE {where_str}
		ORDER BY rt.trip_date DESC
	""", params, as_dict=True)
